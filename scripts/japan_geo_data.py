LON0, LON1, LAT0, LAT1 = 128.5, 146.0, 30.0, 45.8
MAP_W, MAP_H = 48.0, 36.0


def proj(lat, lon):
    """经纬度 → 地图投影坐标 (0..47, 0..35)"""
    return (lon - LON0) / (LON1 - LON0) * (MAP_W - 1), (LAT1 - lat) / (LAT1 - LAT0) * (MAP_H - 1)


def ring(pts):
    return [proj(lat, lon) for lat, lon in pts]


