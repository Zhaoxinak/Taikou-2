# Kruskal MST：在**全部城对**上跑（近邻边只是视觉道路，MST 补边保证全连通）
parent = list(range(len(cities)))

def find(x):
    while parent[x] != x:
        parent[x] = parent[parent[x]]
        x = parent[x]
    return x

def union(a, b):
    ra, rb = find(a), find(b)
    if ra != rb:
        parent[ra] = rb
        return True
    return False

