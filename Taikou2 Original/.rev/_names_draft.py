FEMALE_MARK = u'阿市'          # 女性块从这一项开始
# 尾部 105 男名里**必须留下**的 (公认名将: 按原样取前 500 会把整段尾部连同他们一起砍掉)
TAIL_KEEP = (u'道雪', u'宗茂', u'统虎', u'绍运', u'政宗', u'辉宗', u'义光', u'元亲',
             u'利休', u'织部', u'久秀', u'隆信', u'元秋', u'基次')
EXTRA_DROP = (u'部直', u'信良', u'信安', u'久佐', u'秀氏', u'一宗', u'孝亲', u'安清',
              u'忠音')   # 尾部之外的生僻名: 91 + 9 = 100, 把男名精确凑到 405


def split():
    """去重后按女性标记切成 (男表, 女表)"""
    seen, out = set(), []
    for s in CAND:
        if s in seen:
            continue
        seen.add(s)
        out.append(s)
    k = out.index(FEMALE_MARK)
    return out[:k], out[k:]


def build(n=500):
    """定稿 500 项: 男 405 + 女 95, 每 4 个男名后插 1 个女名。
       砍的是尾部/生僻的男名, 名将一个不丢; 交错排布保证选择框每一页都有女性名。"""
    m, f = split()
    assert len(m) == 505 and len(f) == 95, (len(m), len(f))
    drop = set(x for x in m[-105:] if x not in set(TAIL_KEEP))
    drop |= set(EXTRA_DROP)
    assert len(drop) == len(m) - (n - len(f)), (len(drop), n - len(f))
    assert not (set(EXTRA_DROP) & set(m[-105:])), 'EXTRA_DROP 里有名字已经落在尾部, 数量会算少'
    assert set(EXTRA_DROP) <= set(m), 'EXTRA_DROP 有名字不在男表里'
    mm = [x for x in m if x not in drop]
    out, j = [], 0
    for i, x in enumerate(mm, 1):
        out.append(x)
        if i % 4 == 0 and j < len(f):
            out.append(f[j])
            j += 1
    out += f[j:]                      # 兜底: 男名不足 4 的倍数时剩下的女名接在末尾
    assert len(out) == n and len(set(out)) == n, len(out)
    return tuple(out)


def audit(pool):
    seen, dupes, bad_len, bad_gbk = {}, [], [], []
    for i, n in enumerate(pool):
        try:
            b = n.encode('gbk')
        except UnicodeEncodeError:
            bad_gbk.append(n)
            continue
        if len(b) > 6:
            bad_len.append((n, len(b)))
        if n in seen:
            dupes.append((n, seen[n], i))
        else:
            seen[n] = i
    print('总数 %d  唯一 %d' % (len(pool), len(seen)))
    print('重复 %d 处: %s' % (len(dupes), ', '.join('%s(#%d=#%d)' % d for d in dupes)))
    print('超长 %r' % (bad_len,))
    print('GBK 不可编码 %r' % (bad_gbk,))
    return dupes, bad_len, bad_gbk


if __name__ == '__main__':
    import sys
    sys.stdout.reconfigure(encoding='utf-8', errors='replace')
    audit(CAND)
    print('---- 定稿 ----')
    t = build(500)
    audit(t)
    m, f = split()
    kept = [x for x in t if x in m]
    print('男 %d 女 %d  共 %d' % (len(kept), len(t) - len(kept), len(t)))
    print('被砍的男名: %s' % ' '.join(x for x in m if x not in set(t)))
    if len(sys.argv) > 1:
        with open(sys.argv[1], 'w', encoding='utf-8') as fh:
            for i in range(0, len(t), 10):
                fh.write('    ' + ''.join("u'%s', " % s for s in t[i:i + 10]).rstrip() + '\n')
        print('已写出 %s' % sys.argv[1])
